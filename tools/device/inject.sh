#!/bin/sh
# Device-side evdev injector for slot verification.
# usage: sh inject.sh <seq> [event_node]
# struct input_event = 24B: 16B timeval + u16 type + u16 code + i32 value (LE).
# Key codes are 2 bytes: A=0x130 -> \060\001 ... MENU=0x138 -> \070\001.
z='\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000'
syn='\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000\000'
d=${2:-/dev/input/event1}
case "$1" in
  a_down)      printf "$z\001\000\060\001\001\000\000\000" > "$d" ;;
  a_up)        printf "$z\001\000\060\001\000\000\000\000" > "$d" ;;
  b_down)      printf "$z\001\000\061\001\001\000\000\000" > "$d" ;;
  b_up)        printf "$z\001\000\061\001\000\000\000\000" > "$d" ;;
  y_down)      printf "$z\001\000\062\001\001\000\000\000" > "$d" ;;
  y_up)        printf "$z\001\000\062\001\000\000\000\000" > "$d" ;;
  x_down)      printf "$z\001\000\063\001\001\000\000\000" > "$d" ;;
  x_up)        printf "$z\001\000\063\001\000\000\000\000" > "$d" ;;
  l1_down)     printf "$z\001\000\064\001\001\000\000\000" > "$d" ;;
  l1_up)       printf "$z\001\000\064\001\000\000\000\000" > "$d" ;;
  r1_down)     printf "$z\001\000\065\001\001\000\000\000" > "$d" ;;
  r1_up)       printf "$z\001\000\065\001\000\000\000\000" > "$d" ;;
  select_down) printf "$z\001\000\066\001\001\000\000\000" > "$d" ;;
  select_up)   printf "$z\001\000\066\001\000\000\000\000" > "$d" ;;
  start_down)  printf "$z\001\000\067\001\001\000\000\000" > "$d" ;;
  start_up)    printf "$z\001\000\067\001\000\000\000\000" > "$d" ;;
  menu_down)   printf "$z\001\000\070\001\001\000\000\000" > "$d" ;;
  menu_up)     printf "$z\001\000\070\001\000\000\000\000" > "$d" ;;
  hat_right)   printf "$z\003\000\020\000\001\000\000\000" > "$d" ;;
  hat_left)    printf "$z\003\000\020\000\377\377\377\377" > "$d" ;;
  hat_up)      printf "$z\003\000\021\000\377\377\377\377" > "$d" ;;
  hat_down)    printf "$z\003\000\021\000\001\000\000\000" > "$d" ;;
  hat_none)    printf "$z\003\000\020\000\000\000\000\000" > "$d" ;;
  hat_noney)   printf "$z\003\000\021\000\000\000\000\000" > "$d" ;;
  syn)         : ;;
  *) echo "unknown seq: $1" >&2; exit 2 ;;
esac
printf "%b" "$syn" > "$d"
